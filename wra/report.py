"""Build the final report (Markdown + CSV) from the per-phase findings on disk."""
from __future__ import annotations

import csv
import io
import logging

from . import __version__
from .correlate import merge
from .finding import Finding
from .scoring import score
from .store import RunStore, now_iso

log = logging.getLogger("wra.report")

CSV_FIELDS = ["id", "element", "category", "owasp", "check_id", "title", "phase", "sources", "evidence",
              "pt_outcome", "impact", "likelihood", "risk", "band", "confidence", "rationale", "remediation"]

METHODOLOGY = """\
1. **External (black-box)** - reconnaissance and vulnerability scanning of the URL from the auditor's
   network (passive by default; active scans only with `--active`).
2. **Pentest** - targeted, non-destructive verification of external findings; every check is logged
   with its outcome and evidence (Confirmed / Not confirmed / Not tested / Not assessed).
3. **Internal (white-box)** - agentless, read-only analysis over SSH with authorized credentials:
   source code (SAST), secrets, dependencies, database configuration and permissions, processes,
   services, containers, web server configuration. Heavy tools run on the auditor's machine.
4. **Correlation & scoring** - findings about the same element and issue are merged into one row
   (confidence = number of agreeing sources). Risk = impact x likelihood on a 1-5 scale; every value
   and modifier is justified in the rationale. Checks that could not run are listed as
   *Not assessed* so that coverage is explicit.
"""


def _md(v) -> str:
    s = "" if v is None else str(v)
    return s.replace("\\", "\\\\").replace("|", "\\|").replace("\r", "").replace("\n", "<br>")


def _sort_key(f: Finding):
    return (f.not_assessed, -(f.risk or 0), -(f.confidence or 0), f.element, f.check_id)


def prepare(store: RunStore, low_max: int, medium_max: int) -> list[Finding]:
    findings = [score(f, low_max, medium_max) for f in merge(store.load_all())]
    findings.sort(key=_sort_key)
    for i, f in enumerate(findings, 1):
        f.id = f"WRA-{i:03d}"
    return findings


def render_csv(findings: list[Finding]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=CSV_FIELDS, extrasaction="ignore")
    w.writeheader()
    for f in findings:
        d = f.to_dict()
        d["sources"] = "; ".join(f.sources)
        d["evidence"] = "; ".join(f.evidence)
        d["rationale"] = " | ".join(f.rationale)
        w.writerow(d)
    return buf.getvalue()


def render_markdown(findings: list[Finding], meta: dict, pt_log: list[dict], raw_files: list[str]) -> str:
    scope = meta.get("scope", {})
    access = meta.get("access", {})
    out: list[str] = []
    a = out.append
    a(f"# Web Application Risk Assessment - {_md(scope.get('url', 'unknown target'))}\n")
    a(f"Generated by wra {__version__} on {now_iso()}.\n")

    a("## 1. Scope\n")
    a("| Item | Value |\n|---|---|")
    a(f"| Target URL | {_md(scope.get('url'))} |")
    a(f"| Authorized hosts | {_md(', '.join(scope.get('hosts', [])))} |")
    a(f"| SSH target | {_md(scope.get('ssh') or 'none')} |")
    a(f"| Active scans (`--active`) | {'yes' if meta.get('active') else 'no'} |")
    for n in scope.get("notes", []):
        a(f"| Scope check | {_md(n)} |")
    a("")

    a("## 2. Access level and coverage\n")
    a(f"- **Access level used:** `{access.get('effective', 'unknown')}` "
      f"(detected: `{access.get('detected', 'n/a')}`, ceiling: `{access.get('ceiling', 'auto')}`)")
    for d in access.get("details", []):
        a(f"  - {_md(d)}")
    cov = meta.get("coverage", {})
    if cov:
        a("\n| Phase | Check | Source | Status | Notes |\n|---|---|---|---|---|")
        for phase, entries in cov.items():
            for e in entries:
                a(f"| {phase} | {_md(e.get('probe'))} | {_md(e.get('source'))} | {_md(e.get('status'))} | {_md(e.get('reason'))} |")
    else:
        a("\nNo phase has been executed yet.")
    a("")

    a("## 3. Methodology\n")
    a(METHODOLOGY)

    scored = [f for f in findings if not f.not_assessed]
    a("## 4. Summary\n")
    a("| Band | Findings |\n|---|---|")
    for b in ("high", "medium", "low"):
        a(f"| {b} | {sum(1 for f in scored if f.band == b)} |")
    a(f"| not assessed | {sum(1 for f in findings if f.not_assessed)} |\n")

    a("## 5. Findings (external + internal, single table, sorted by risk)\n")
    if not findings:
        a("No findings.\n")
    else:
        a("| ID | Element | Category | Issue | Sources | Evidence | PT outcome | I | L | Risk | Rationale |")
        a("|---|---|---|---|---|---|---|---|---|---|---|")
        for f in findings:
            ev = "<br>".join(f"[{_md(e.split('/')[-1])}]({e})" for e in f.evidence) or "-"
            risk = f"**{f.risk}** {f.band}" if f.risk is not None else "-"
            cat = f.category + (f" / {f.owasp}" if f.owasp else "")
            a(f"| {f.id} | {_md(f.element)} | {_md(cat)} | {_md(f.title)} | {_md(', '.join(f.sources))} "
              f"(x{f.confidence}) | {ev} | {_md(f.pt_outcome)} | {f.impact or '-'} | {f.likelihood or '-'} | {risk} "
              f"| {_md('; '.join(f.rationale))} |")
        a("")

    a("## 6. Finding details\n")
    for f in findings:
        if f.not_assessed:
            continue
        a(f"### {f.id} - {_md(f.title)}\n")
        a(f"- **Element:** {_md(f.element)}")
        a(f"- **Category:** {_md(f.category)}{(' / OWASP ' + f.owasp) if f.owasp else ''}")
        a(f"- **Sources:** {_md(', '.join(f.sources))} (confidence {f.confidence})")
        a(f"- **PT outcome:** {_md(f.pt_outcome)}")
        a(f"- **Risk:** {f.risk} ({f.band}) = impact {f.impact} x likelihood {f.likelihood}")
        if f.description:
            a(f"- **Description:** {_md(f.description)}")
        a("- **Rationale:**")
        for r in f.rationale:
            a(f"  - {_md(r)}")
        if f.remediation:
            a(f"- **Remediation:** {_md(f.remediation)}")
        if f.evidence:
            a("- **Evidence:** " + ", ".join(f"[{_md(e)}]({e})" for e in f.evidence))
        a("")

    a("## 7. Penetration test log\n")
    if pt_log:
        a("| # | Check | Target | Outcome | Evidence | Notes |\n|---|---|---|---|---|---|")
        for i, e in enumerate(pt_log, 1):
            ev = "<br>".join(f"[{_md(x.split('/')[-1])}]({x})" for x in e.get("evidence", [])) or "-"
            a(f"| {i} | {_md(e.get('check'))} | {_md(e.get('target'))} | {_md(e.get('outcome'))} | {ev} | {_md(e.get('notes'))} |")
    else:
        a("The pentest phase has not been executed.")
    a("")

    a("## Appendix - raw outputs\n")
    if raw_files:
        for r in raw_files:
            a(f"- [{_md(r)}]({r})")
    else:
        a("No raw outputs.")
    a("")
    return "\n".join(out)


def build_report(store: RunStore, low_max: int = 6, medium_max: int = 12) -> tuple[str, str, int]:
    findings = prepare(store, low_max, medium_max)
    md = render_markdown(findings, store.meta(), store.load_pt_log(), store.list_raw())
    md_path = store.root / "report.md"
    csv_path = store.root / "findings.csv"
    store._write(md_path, md)
    store._write(csv_path, render_csv(findings))
    return store.rel(md_path), store.rel(csv_path), len(findings)
